const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const test = require("node:test");

const root = path.resolve(__dirname, "..");
const read = file => fs.readFileSync(path.join(root, file), "utf8");
const migration = read("supabase/migrations/20261102120000_submission_rate_limit.sql");
const rollback = read("supabase/migrations/20261102120000_submission_rate_limit.rollback.sql");
const edge = read("supabase/functions/submit-catalogue-request/index.ts");

function rate(state, hash, key, short = 10, long = 50) {
  if (state.requests.has(key)) return { replayed: true, allowed: true };
  const attempts = state.attempts.get(hash) || [];
  if (attempts.filter(age => age < 10).length >= short || attempts.filter(age => age < 1440).length >= long) return { allowed: false, retryAfter: 1 };
  attempts.push(0); state.attempts.set(hash, attempts); state.requests.add(key);
  return { allowed: true, replayed: false };
}

test("rate-limit migration uses hashed identities, atomic locks, and service-role-only execution", () => {
  assert.match(migration, /drop column if exists ip/);
  assert.match(migration, /client_hash text/);
  assert.match(migration, /alter column id add generated by default as identity/);
  assert.match(migration, /security definer/);
  assert.match(migration, /set search_path to public, private, pg_temp/);
  assert.match(migration, /hashtextextended\(key_text, 0\)/);
  assert.match(migration, /hashtextextended\('catalogue-request-rate:'\|\|p_client_hash, 0\)/);
  assert.ok(migration.indexOf("hashtextextended(key_text, 0)") < migration.indexOf("catalogue-request-rate:"));
  assert.match(migration, /where idempotency_key=key_text::uuid/);
  assert.match(migration, /p_short_limit not between 1 and 1000/);
  assert.match(migration, /p_long_limit not between p_short_limit and 1000/);
  assert.match(migration, /revoke all on function .* from public, anon, authenticated/);
  assert.match(migration, /grant execute .* to service_role/);
  assert.match(rollback, /drop function if exists public\.submit_catalogue_request_with_rate_limit/);
});

test("new submissions consume quota, concurrent-equivalent new keys stop at the threshold, and replays do not", () => {
  const state = { attempts: new Map(), requests: new Set() };
  for (let index = 0; index < 10; index++) assert.equal(rate(state, "network", "key-" + index).allowed, true);
  assert.equal(rate(state, "network", "key-10").allowed, false);
  assert.deepEqual(rate(state, "other-network", "key-0"), { replayed: true, allowed: true });
  assert.equal(state.attempts.get("other-network"), undefined);
});

test("Edge Function trusts only the platform address, fails closed, returns 429, and preserves drafts", () => {
  assert.match(edge, /req\.headers\.get\("cf-connecting-ip"\)/);
  assert.doesNotMatch(edge, /x-forwarded-for|x-real-ip/);
  assert.match(edge, /CATALOGUE_RATE_LIMIT_PEPPER/);
  assert.match(edge, /CATALOGUE_RATE_LIMIT_10M/);
  assert.match(edge, /CATALOGUE_RATE_LIMIT_24H/);
  assert.match(edge, /submit_catalogue_request_with_rate_limit/);
  assert.match(edge, /rateLimited===true/);
  assert.match(edge, /"Retry-After"/);
  assert.match(edge, /if\(!hash\)return json\(\{ok:false,error:"Submission service is temporarily unavailable/);
  const submission = read("js/request-submission.js");
  assert.match(submission, /if\(!response\.ok.*throw new Error/);
  assert.match(submission, /clearSubmittedDraft/);
});
